"""Failure-mode breakdown across configs/seeds.

Reads the per-query eval_score.json files produced by run_pilot_eval.py and
prints the GPT-4o-style "what fails" table: how many plans fail each named
constraint check, plus the Stage-0/1 (runner-error / non-delivery) taxonomy.

Requires eval_score.json to carry per-check detail, i.e. it must have been
generated by the current run_pilot_eval.py (older files lack `commonsense_detail`
and need re-running the eval). The parsed plans are also persisted under
parsed_plans/, so re-running the eval to refresh detail needs no API re-parsing
beyond the first pass.

Usage (from TravelPlanner root):

    python -m eval_runner.failure_modes \
        --results-root results/rq1_qwen14b \
        --split validation \
        --configs single_react planner_executor \
        --seeds 0 1 2
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

# Cluster login shells default to a latin-1 locale; force UTF-8 for the
# em-dashes / ⚠️ in the report.
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

_ROOT = Path(__file__).resolve().parent.parent

COMMONSENSE_KEYS = [
    "is_reasonable_visiting_city",
    "is_valid_restaurants",
    "is_valid_attractions",
    "is_valid_accommodation",
    "is_valid_transportation",
    "is_valid_information_in_current_city",
    "is_valid_information_in_sandbox",
    "is_not_absent",
]
HARD_KEYS = [
    "valid_cuisine",
    "valid_room_rule",
    "valid_transportation",
    "valid_room_type",
    "valid_cost",
]
# Stage 0/1 reasons in display order; constraint_fail/pass handled separately.
REASON_ORDER = [
    "runner_error",
    "not_run",
    "max_token_exceeded",
    "empty_answer",
    "parse_failed",
    "eval_crash",
    "undelivered_other",
    "constraint_fail",
    "pass",
]


def _load_seed(results_root: str, config: str, split: str, seed: int) -> Optional[List[Dict[str, Any]]]:
    p = _ROOT / results_root / config / split / f"seed{seed}" / "eval_score.json"
    if not p.exists():
        return None
    return json.loads(p.read_text(encoding="utf-8"))


def _aggregate(rows_per_seed: List[List[Dict[str, Any]]]) -> Dict[str, Any]:
    n_seeds = len(rows_per_seed)
    n_q = sum(len(r) for r in rows_per_seed)
    has_detail = any("commonsense_detail" in rec for rows in rows_per_seed for rec in rows)

    reasons: Dict[str, int] = {}
    cs_fail: Dict[str, int] = {k: 0 for k in COMMONSENSE_KEYS}
    hard_fail: Dict[str, int] = {k: 0 for k in HARD_KEYS}
    delivered = cs_macro = hard_macro = final = 0

    for rows in rows_per_seed:
        for rec in rows:
            reasons[rec.get("failure_reason", "unknown")] = reasons.get(rec.get("failure_reason", "unknown"), 0) + 1
            if rec.get("delivered"):
                delivered += 1
            if rec.get("commonsense_pass") is True:
                cs_macro += 1
            if rec.get("hard_pass") is True:
                hard_macro += 1
            if rec.get("final_pass") is True:
                final += 1
            for k in rec.get("commonsense_detail", {}).get("failed", []):
                cs_fail[k] = cs_fail.get(k, 0) + 1
            for k in rec.get("hard_detail", {}).get("failed", []):
                hard_fail[k] = hard_fail.get(k, 0) + 1

    return {
        "n_seeds": n_seeds,
        "n_q": n_q,
        "has_detail": has_detail,
        "reasons": reasons,
        "cs_fail": cs_fail,
        "hard_fail": hard_fail,
        "delivered": delivered,
        "cs_macro": cs_macro,
        "hard_macro": hard_macro,
        "final": final,
    }


def _cell(count: int, n_q: int) -> str:
    """count (and % of all queries)."""
    pct = (100.0 * count / n_q) if n_q else 0.0
    return f"{count} ({pct:.0f}%)"


def _table(title: str, row_labels: List[str], counts_by_config: Dict[str, Dict[str, int]],
           n_q_by_config: Dict[str, int]) -> str:
    configs = list(counts_by_config.keys())
    lines = [f"\n### {title}\n"]
    header = "| Check | " + " | ".join(configs) + " |"
    sep = "|" + "---|" * (len(configs) + 1)
    lines.append(header)
    lines.append(sep)
    for label in row_labels:
        cells = [_cell(counts_by_config[c].get(label, 0), n_q_by_config[c]) for c in configs]
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results-root", required=True, help="e.g. results/rq1_qwen14b")
    ap.add_argument("--split", default="validation", choices=["pilot", "validation", "test"])
    ap.add_argument("--configs", nargs="+", default=["single_react", "planner_executor"])
    ap.add_argument("--seeds", nargs="+", type=int, default=[0, 1, 2])
    ap.add_argument("--json", action="store_true", help="emit machine-readable JSON instead of markdown")
    args = ap.parse_args()

    agg_by_config: Dict[str, Dict[str, Any]] = {}
    missing: List[str] = []
    for config in args.configs:
        rows_per_seed = []
        for seed in args.seeds:
            rows = _load_seed(args.results_root, config, args.split, seed)
            if rows is None:
                missing.append(f"{config}/seed{seed}")
                continue
            rows_per_seed.append(rows)
        if rows_per_seed:
            agg_by_config[config] = _aggregate(rows_per_seed)

    if args.json:
        print(json.dumps({"results_root": args.results_root, "split": args.split,
                          "by_config": agg_by_config, "missing": missing}, indent=2))
        return

    print(f"# Failure-mode breakdown — {args.results_root} / {args.split}")
    if missing:
        print(f"\n> ⚠️ missing eval_score.json: {', '.join(missing)}")
    no_detail = [c for c, a in agg_by_config.items() if not a["has_detail"]]
    if no_detail:
        print(f"\n> ⚠️ no per-check detail for {no_detail} — re-run run_pilot_eval.py "
              f"(current version) to populate `commonsense_detail`/`hard_detail`. "
              f"Stage-2/3 rows below will be blank for these.")

    n_q_by_config = {c: a["n_q"] for c, a in agg_by_config.items()}
    print("\n_Cells are plan counts (and % of all scored plans) summed over "
          f"seeds {args.seeds}; denominator = n_seeds × n_queries._")
    for c, a in agg_by_config.items():
        print(f"\n- **{c}**: {a['n_seeds']} seed(s) × ~{a['n_q'] // max(a['n_seeds'],1)} = {a['n_q']} plans  "
              f"| delivered {a['delivered']} | CS-macro {a['cs_macro']} | "
              f"hard-macro {a['hard_macro']} | **final-pass {a['final']}**")

    # Stage 0/1 taxonomy
    print(_table("Stage 0/1 — outcome taxonomy (mutually exclusive)",
                 REASON_ORDER,
                 {c: a["reasons"] for c, a in agg_by_config.items()},
                 n_q_by_config))
    # Stage 2 — commonsense
    print(_table("Stage 2 — commonsense check failures (plans failing each check)",
                 COMMONSENSE_KEYS,
                 {c: a["cs_fail"] for c, a in agg_by_config.items()},
                 n_q_by_config))
    # Stage 3 — hard (gated behind is_not_absent + is_valid_information_in_sandbox)
    print(_table("Stage 3 — hard check failures (only counted on plans that clear "
                 "is_not_absent + is_valid_information_in_sandbox)",
                 HARD_KEYS,
                 {c: a["hard_fail"] for c, a in agg_by_config.items()},
                 n_q_by_config))


if __name__ == "__main__":
    main()
